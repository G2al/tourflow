    <p>I voli si vendono abbinati a un hotel. Funziona in due passi:</p>
    <ol style="padding-left: 20px; list-style: decimal;">
        <li><strong>Crei i voli</strong> in <em>Catalogo → Voli</em>: aeroporto di partenza, date di andata e ritorno, posti acquistati e prezzo a persona (adulto, bambino, infant). Per partenze settimanali usa "Duplica" e cambia solo le date.</li>
        <li><strong>Li abbini al pacchetto</strong> qui: compare l'elenco dei voli futuri della destinazione e spunti quelli da proporre con questo hotel.</li>
    </ol>

    <div class="tf-example">
        <strong>Esempio</strong><br>
        Volo Napoli → Hurghada dal 15/11 al 22/11, 290 € a persona. Hotel a 70 € a notte. 2 adulti:<br>
        hotel 70 € × 7 notti × 2 = 980 € + volo 290 € × 2 = 580 € → <strong>1.560 €</strong> (più i trasferimenti, se a pagamento).
    </div>

    <h3>Da sapere</h3>
    <ul>
        <li>Le <strong>notti in hotel sono quelle del volo</strong>: il cliente sceglie il volo, non le date.</li>
        <li>Nei prezzi per stagione metti <strong>solo l'hotel</strong>: il prezzo del volo è già nel volo.</li>
        <li>I <strong>posti</strong> si scalano a ogni opzione e conferma. Gli infant non occupano posto.</li>
        <li>Lo stesso volo può essere abbinato a più hotel: in quel caso i posti sono condivisi (è lo stesso aereo).</li>
        <li>Nel <strong>solo soggiorno</strong>, attivando "Permetti di aggiungere il volo", il cliente può scegliere se venire con il proprio volo o aggiungerne uno dei tuoi.</li>
    </ul>
